-- ============ tvac-3：地面站二进制解码结果分片重组 ============

-- 帧重组会话：一个带帧号的逻辑帧由多个通道分片构成，分片允许乱序到达、重复重发
CREATE TABLE IF NOT EXISTS t_tvac_frame_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_key VARCHAR(96) NOT NULL,
    frame_no VARCHAR(64) NOT NULL,
    article_id BIGINT NOT NULL,
    plan_id BIGINT NOT NULL,
    expected_pieces INT,
    good_pieces INT NOT NULL DEFAULT 0,
    bad_pieces INT NOT NULL DEFAULT 0,
    source_device VARCHAR(64),
    -- ASSEMBLING：收片中；ASSEMBLED：触发重组，按通道产出遥测帧，坏通道隔离留痕
    status VARCHAR(16) NOT NULL DEFAULT 'ASSEMBLING',
    assembled_time TIMESTAMP,
    remark VARCHAR(512),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tvac_frame_session_key UNIQUE (session_key),
    CONSTRAINT fk_tvac_frame_session_article FOREIGN KEY (article_id) REFERENCES t_tvac_article(id),
    CONSTRAINT fk_tvac_frame_session_plan FOREIGN KEY (plan_id) REFERENCES t_tvac_plan(id)
);

-- 帧分片：某通道在某片序号上的二进制解码结果，到片即复算 CRC32 分片校验和
CREATE TABLE IF NOT EXISTS t_tvac_frame_piece (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    channel_id BIGINT NOT NULL,
    piece_seq INT NOT NULL,
    receive_seq INT NOT NULL,
    payload CLOB,
    raw_value VARCHAR(256),
    eng_value DECIMAL(16,4),
    cycle_no INT,
    frame_time TIMESTAMP,
    client_checksum VARCHAR(16),
    server_checksum VARCHAR(16),
    -- VERIFIED：校验通过；BAD：校验和不符（单通道坏帧，隔离不影响其他通道）；
    -- DUPLICATED：重复片（地面站重发），校验一致直接幂等丢弃
    status VARCHAR(16) NOT NULL DEFAULT 'VERIFIED',
    bad_reason VARCHAR(256),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tvac_frame_piece UNIQUE (session_id, channel_id, piece_seq),
    CONSTRAINT fk_tvac_frame_piece_session FOREIGN KEY (session_id) REFERENCES t_tvac_frame_session(id),
    CONSTRAINT fk_tvac_frame_piece_channel FOREIGN KEY (channel_id) REFERENCES t_tvac_channel(id)
);
CREATE INDEX IF NOT EXISTS idx_tvac_frame_piece_session ON t_tvac_frame_piece (session_id, status);

-- ============ tvac-4：时序判读规则版本化与业务区间计算 ============

-- 时序判读规则集：挂在对象（试验件）上，mission_tz 为任务时区（观测以设备 UTC 为源，按此时区归区间）
CREATE TABLE IF NOT EXISTS t_tvac_rule_set (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_code VARCHAR(64) NOT NULL,
    set_name VARCHAR(128) NOT NULL,
    article_id BIGINT NOT NULL,
    -- 任务时区（IANA 时区ID，如 Asia/Shanghai），建档后不可改
    mission_tz VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
    remark VARCHAR(512),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tvac_rule_set_code UNIQUE (set_code),
    CONSTRAINT fk_tvac_rule_set_article FOREIGN KEY (article_id) REFERENCES t_tvac_article(id)
);
CREATE INDEX IF NOT EXISTS idx_tvac_rule_set_article ON t_tvac_rule_set (article_id);

-- 规则版本：同一规则集内版本号递增；DRAFT 可改区间，启用后不能原地修改，换版只能新建版本
CREATE TABLE IF NOT EXISTS t_tvac_rule_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    -- DRAFT：草稿可改；ENABLED：启用（同集仅一个启用版，启用新版自动停用旧版）；DISABLED：已停用
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    enabled_time TIMESTAMP,
    remark VARCHAR(512),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tvac_rule_version UNIQUE (set_id, version_no),
    CONSTRAINT fk_tvac_rule_version_set FOREIGN KEY (set_id) REFERENCES t_tvac_rule_set(id)
);

-- 规则区间（业务区间）：任务时区当日分钟 [start_min, end_min) 左闭右开；
-- end_min <= start_min 表示跨日（如 22:00-次日10:00）；同版本内区间重叠必须拒绝
CREATE TABLE IF NOT EXISTS t_tvac_rule_band (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    -- PEAK 峰值 / FLAT 平段 / VALLEY 谷值
    band_type VARCHAR(16) NOT NULL,
    start_min INT NOT NULL,
    end_min INT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT fk_tvac_rule_band_version FOREIGN KEY (version_id) REFERENCES t_tvac_rule_version(id)
);
CREATE INDEX IF NOT EXISTS idx_tvac_rule_band_version ON t_tvac_rule_band (version_id);

-- 区间计算批次：同一（规则版本 + UTC 窗口）唯一，重算幂等返回原批次；
-- 并发重算由 uk_tvac_calc_run_scope 兜底，不会产生两份结果
CREATE TABLE IF NOT EXISTS t_tvac_calc_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_no VARCHAR(64) NOT NULL,
    set_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    article_id BIGINT NOT NULL,
    -- 计算窗口（设备 UTC，左闭右开）
    window_start_utc TIMESTAMP NOT NULL,
    window_end_utc TIMESTAMP NOT NULL,
    mission_tz VARCHAR(64) NOT NULL,
    -- 计算采用的规则区间快照（JSON），历史结果读取以快照为准，换版不污染
    snapshot_json CLOB NOT NULL,
    obs_count INT NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'DONE',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tvac_calc_run_no UNIQUE (run_no),
    CONSTRAINT uk_tvac_calc_run_scope UNIQUE (version_id, window_start_utc, window_end_utc),
    CONSTRAINT fk_tvac_calc_run_set FOREIGN KEY (set_id) REFERENCES t_tvac_rule_set(id),
    CONSTRAINT fk_tvac_calc_run_version FOREIGN KEY (version_id) REFERENCES t_tvac_rule_version(id),
    CONSTRAINT fk_tvac_calc_run_article FOREIGN KEY (article_id) REFERENCES t_tvac_article(id)
);
CREATE INDEX IF NOT EXISTS idx_tvac_calc_run_set ON t_tvac_calc_run (set_id, id);
CREATE INDEX IF NOT EXISTS idx_tvac_calc_run_article ON t_tvac_calc_run (article_id, id);

-- 计算明细：每区间一行；累计值 BigDecimal 全精度累加，均值仅在最终步骤统一舍入
CREATE TABLE IF NOT EXISTS t_tvac_calc_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    band_id BIGINT NOT NULL,
    band_type VARCHAR(16) NOT NULL,
    start_min INT NOT NULL,
    end_min INT NOT NULL,
    obs_count INT NOT NULL DEFAULT 0,
    sum_value DECIMAL(28,4),
    min_value DECIMAL(16,4),
    max_value DECIMAL(16,4),
    avg_value DECIMAL(28,4),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT fk_tvac_calc_detail_run FOREIGN KEY (run_id) REFERENCES t_tvac_calc_run(id)
);
CREATE INDEX IF NOT EXISTS idx_tvac_calc_detail_run ON t_tvac_calc_detail (run_id);

