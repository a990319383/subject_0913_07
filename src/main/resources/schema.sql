-- ============ tvac-3：观测数据 CSV 批量导入 ============

-- 导入批次：文件级 SHA-256 校验和唯一，重传同一文件直接返回原批次（文件幂等）
CREATE TABLE IF NOT EXISTS t_tvac_import_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no VARCHAR(64) NOT NULL,
    file_name VARCHAR(255),
    file_checksum VARCHAR(64) NOT NULL,
    total_rows INT NOT NULL DEFAULT 0,
    success_count INT NOT NULL DEFAULT 0,
    updated_count INT NOT NULL DEFAULT 0,
    failed_count INT NOT NULL DEFAULT 0,
    shard_size INT NOT NULL DEFAULT 5000,
    shard_count INT NOT NULL DEFAULT 0,
    -- PROCESSING：仍有分片在处理；COMPLETED：全部分片处理完毕（允许存在逐行失败）
    status VARCHAR(16) NOT NULL DEFAULT 'PROCESSING',
    error_message VARCHAR(1000),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tvac_import_checksum UNIQUE (file_checksum),
    CONSTRAINT uk_tvac_import_batch_no UNIQUE (batch_no)
);

-- 导入分片：按固定行数切分，独立事务、独立校验和；FAILED 分片可用原报文重试验跑
CREATE TABLE IF NOT EXISTS t_tvac_import_shard (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    shard_no INT NOT NULL,
    line_start INT NOT NULL,
    line_end INT NOT NULL,
    row_count INT NOT NULL DEFAULT 0,
    success_count INT NOT NULL DEFAULT 0,
    updated_count INT NOT NULL DEFAULT 0,
    failed_count INT NOT NULL DEFAULT 0,
    -- 本分片原文的 CRC32 校验和（hex），重试时复算比对，防止重试串片
    shard_checksum VARCHAR(16) NOT NULL,
    -- 分片原始报文，失败分片重试时重新解析（业务键幂等保证重试不重复落库）
    shard_payload CLOB,
    -- PENDING/PROCESSING/SUCCESS/FAILED
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempts INT NOT NULL DEFAULT 0,
    error_message VARCHAR(1000),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tvac_import_shard UNIQUE (batch_id, shard_no),
    CONSTRAINT fk_tvac_import_shard_batch FOREIGN KEY (batch_id) REFERENCES t_tvac_import_batch(id)
);

-- 逐行结果：成功/更新/失败全部留痕，失败行同时写错误明细表
CREATE TABLE IF NOT EXISTS t_tvac_import_row (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    shard_no INT NOT NULL,
    line_no INT NOT NULL,
    record_type VARCHAR(16),
    biz_key VARCHAR(256),
    object_code VARCHAR(64),
    -- SUCCESS：新增；UPDATED：命中业务键且未锁定，执行覆盖；FAILED：校验/锁定失败
    result VARCHAR(16) NOT NULL,
    target_table VARCHAR(32),
    target_id BIGINT,
    create_time TIMESTAMP,
    CONSTRAINT fk_tvac_import_row_batch FOREIGN KEY (batch_id) REFERENCES t_tvac_import_batch(id)
);
CREATE INDEX IF NOT EXISTS idx_tvac_import_row_batch ON t_tvac_import_row (batch_id, line_no);

-- 错误明细：保留原始行号、字段、原值与失败原因，供地面站整改后重发
CREATE TABLE IF NOT EXISTS t_tvac_import_error (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    shard_no INT NOT NULL,
    line_no INT NOT NULL,
    record_type VARCHAR(16),
    biz_key VARCHAR(256),
    field_name VARCHAR(64) NOT NULL,
    raw_value VARCHAR(1000),
    reason VARCHAR(512) NOT NULL,
    create_time TIMESTAMP,
    CONSTRAINT fk_tvac_import_error_batch FOREIGN KEY (batch_id) REFERENCES t_tvac_import_batch(id)
);
CREATE INDEX IF NOT EXISTS idx_tvac_import_error_batch ON t_tvac_import_error (batch_id, line_no);

-- 归一化观测数据台账：record_type + 业务键唯一，是文件校验和之外的第二道幂等防线
